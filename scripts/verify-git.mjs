import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, cpSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = resolve(dirname(fileURLToPath(import.meta.url)), '../examples/site-da-turma');
const tempBase = realpathSync(tmpdir());
const temporary = mkdtempSync(join(tempBase, 'oficina git verification '));
const a = join(temporary, 'pessoa A');
const b = join(temporary, 'pessoa B');
const remote = join(temporary, 'remoto local.git');
const git = (cwd, args, expected = 0) => {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8', shell: false,
    env: { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: join(temporary, 'empty-config'), GIT_TERMINAL_PROMPT: '0' } });
  if (result.error) throw result.error;
  assert.equal(result.status, expected, `git ${args.join(' ')}\n${result.stdout}\n${result.stderr}`);
  return result.stdout.trim();
};
const configure = (repo, name) => {
  git(repo, ['config', '--local', 'user.name', name]);
  git(repo, ['config', '--local', 'user.email', 'oficina@example.invalid']);
  git(repo, ['config', '--local', 'core.autocrlf', 'false']);
};
const write = (repo, file, content) => writeFileSync(join(repo, file), content.replace(/\r\n?/g, '\n'), 'utf8');
const commit = (repo, message) => git(repo, ['commit', '-m', message]);
const head = repo => git(repo, ['rev-parse', 'HEAD']);
const clean = repo => assert.equal(git(repo, ['status', '--porcelain']), '');
const replace = (repo, before, after) => {
  const content = readFileSync(join(repo, 'index.html'), 'utf8');
  assert.ok(content.includes(before));
  write(repo, 'index.html', content.replace(before, after));
};
try {
  mkdirSync(a);
  cpSync(source, a, { recursive: true });
  git(a, ['init', '-b', 'main']);
  configure(a, 'Pessoa A');
  git(a, ['add', 'index.html', 'styles.css', 'README.md']);
  commit(a, 'Base da turma');
  const base = head(a);
  write(a, '.gitignore', 'rascunhos/\n');
  mkdirSync(join(a, 'rascunhos'));
  write(a, 'rascunhos/notas.txt', 'Não versionar\n');
  assert.equal(git(a, ['check-ignore', 'rascunhos/notas.txt']), 'rascunhos/notas.txt');
  git(a, ['add', '.gitignore']);
  commit(a, 'Ignora rascunhos');
  replace(a, '<h1>Site da turma</h1>', '<h1>Turma em construção</h1>');
  git(a, ['add', 'index.html']);
  const staged = git(a, ['show', ':index.html']);
  replace(a, '<h1>Turma em construção</h1>', '<h1>Turma colaborativa</h1>');
  assert.equal(git(a, ['show', ':index.html']), staged);
  assert.ok(git(a, ['diff', '--', 'index.html']).includes('Turma colaborativa'));
  commit(a, 'Registra snapshot preparado');
  assert.equal(git(a, ['show', 'HEAD:index.html']), staged);
  git(a, ['add', 'index.html']);
  commit(a, 'Registra edição restante');
  replace(a, 'Este projeto pequeno será modificado', 'Este projeto será modificado');
  git(a, ['add', 'index.html']);
  assert.ok(git(a, ['diff', '--cached', '--', 'index.html']).includes('Este projeto será modificado'));
  git(a, ['restore', '--staged', 'index.html']);
  assert.equal(git(a, ['diff', '--cached']), '');
  assert.ok(readFileSync(join(a, 'index.html'), 'utf8').includes('Este projeto será modificado'));
  git(a, ['add', 'index.html']);
  commit(a, 'Testa uma nova frase');
  const reverted = head(a);
  const previousTree = git(a, ['rev-parse', 'HEAD~1^{tree}']);
  clean(a);
  git(a, ['revert', '--no-edit', 'HEAD']);
  assert.equal(git(a, ['rev-parse', 'HEAD^{tree}']), previousTree);
  git(a, ['merge-base', '--is-ancestor', reverted, 'HEAD']);
  git(a, ['switch', '-c', 'melhoria-descricao']);
  write(a, 'README.md', readFileSync(join(a, 'README.md'), 'utf8') + '\nNossa descrição melhorou.\n');
  git(a, ['add', 'README.md']);
  commit(a, 'Melhora descrição');
  const feature = head(a);
  git(a, ['switch', 'main']);
  git(a, ['merge', '--ff-only', 'melhoria-descricao']);
  assert.equal(head(a), feature);
  git(a, ['switch', '-c', 'mensagem-alternativa']);
  replace(a, 'Aprendemos Git em conjunto.', 'Aprendemos criando.');
  git(a, ['add', 'index.html']);
  commit(a, 'Mensagem alternativa');
  const branchTip = head(a);
  git(a, ['switch', 'main']);
  replace(a, 'Aprendemos Git em conjunto.', 'Aprendemos colaborando.');
  git(a, ['add', 'index.html']);
  commit(a, 'Mensagem principal');
  const mainTip = head(a);
  clean(a);
  git(a, ['merge', 'mensagem-alternativa'], 1);
  assert.ok(git(a, ['ls-files', '-u']).includes('index.html'));
  assert.ok(readFileSync(join(a, 'index.html'), 'utf8').includes('<<<<<<<'));
  git(a, ['merge', '--abort']);
  assert.equal(head(a), mainTip);
  clean(a);
  git(a, ['merge', 'mensagem-alternativa'], 1);
  write(a, 'index.html', git(a, ['show', 'HEAD:index.html']).replace('Aprendemos colaborando.', 'Aprendemos criando e colaborando.') + '\n');
  assert.equal(git(a, ['diff', '--check']), '');
  git(a, ['add', 'index.html']);
  commit(a, 'Combina as mensagens');
  assert.deepEqual(git(a, ['show', '-s', '--format=%P', 'HEAD']).split(' '), [mainTip, branchTip]);
  for (const ancestor of [base, reverted, feature, branchTip]) git(a, ['merge-base', '--is-ancestor', ancestor, 'HEAD']);
  git(temporary, ['init', '--bare', '-b', 'main', remote]);
  git(a, ['remote', 'add', 'origin', remote]);
  git(a, ['push', '-u', 'origin', 'main']);
  git(temporary, ['clone', remote, b]);
  configure(b, 'Pessoa B');
  git(b, ['switch', '-c', 'melhoria-dupla']);
  write(b, 'README.md', readFileSync(join(b, 'README.md'), 'utf8') + '\nProposta de B revisada por A.\n');
  git(b, ['add', 'README.md']);
  commit(b, 'Propõe melhoria');
  const proposal = head(b);
  git(b, ['push', '-u', 'origin', 'melhoria-dupla']);
  git(a, ['fetch', 'origin']);
  assert.ok(git(a, ['diff', 'main...origin/melhoria-dupla']).includes('Proposta de B'));
  git(a, ['merge', '--no-ff', 'origin/melhoria-dupla', '-m', 'Integra proposta revisada']);
  assert.equal(git(a, ['show', '-s', '--format=%P', 'HEAD']).split(' ').length, 2);
  git(a, ['push', 'origin', 'main']);
  git(b, ['switch', 'main']);
  git(b, ['pull', '--ff-only']);
  git(a, ['pull', '--ff-only']);
  assert.equal(head(a), head(b));
  git(b, ['merge-base', '--is-ancestor', proposal, 'HEAD']);
  clean(a); clean(b);
  console.log(`PASS: snapshot, unstage, revert, fast-forward, conflito/abort/resolução, dois pais, histórico, push/fetch/pull local (${process.platform}; ${git(a, ['--version'])}). GitHub/PR não exercitados.`);
} finally {
  const actual = realpathSync(temporary);
  assert.equal(dirname(actual), tempBase);
  assert.ok(basename(actual).startsWith('oficina git verification '));
  assert.notEqual(actual, tempBase);
  rmSync(actual, { recursive: true, force: true });
}
